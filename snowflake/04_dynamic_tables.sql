-- On-demand snapshots. No automatic freshness claim.
USE DATABASE IDENTIFIER($DEMO_DB);
USE SCHEMA CURATED;
USE WAREHOUSE IDENTIFIER($DEMO_WH);

CREATE DYNAMIC TABLE CURATED.PERFORMANCE_SUMMARY
  TARGET_LAG = DOWNSTREAM WAREHOUSE = __DEMO_WH__
  REFRESH_MODE = FULL INITIALIZE = ON_CREATE
AS
SELECT berth.ID AS ENTITY_ID, berth.NAME AS ENTITY_NAME,
       berth.REGION, berth.CATEGORY, berth.STATUS,
       COUNT(*) AS EVENT_COUNT, SUM(observation.DISRUPTION_COUNT) AS DISRUPTION_COUNT,
       SUM(observation.OPERATING_HOURS) AS OPERATING_HOURS,
       SUM(observation.PLANNED_HOURS) AS PLANNED_HOURS,
       SUM(observation.DOWNTIME_HOURS) AS DOWNTIME_HOURS,
       SUM(observation.PM_DUE) AS PM_DUE, SUM(observation.PM_COMPLETED) AS PM_COMPLETED,
       SUM(observation.YARD_MOVES) AS YARD_MOVES,
       SUM(observation.ON_TIME_MOVES) AS ON_TIME_MOVES, SUM(observation.BOX_MOVES) AS BOX_MOVES,
       SUM(observation.REHANDLE_MOVES) AS REHANDLE_MOVES,
       100.0 * SUM(observation.ON_TIME_MOVES) / NULLIF(SUM(observation.BOX_MOVES), 0) AS ON_TIME_PCT,
       1000.0 * SUM(observation.REHANDLE_MOVES) / NULLIF(SUM(observation.YARD_MOVES), 0) AS REHANDLES_PER_1K,
       100.0 * SUM(observation.OPERATING_HOURS) / NULLIF(SUM(observation.PLANNED_HOURS), 0) AS EQUIPMENT_UPTIME_PCT,
       100.0 * SUM(observation.PM_COMPLETED) / NULLIF(SUM(observation.PM_DUE), 0) AS PM_COMPLIANCE_PCT,
       MAX(observation.EVENT_DATE) AS SOURCE_WATERMARK
FROM RAW.BERTH_DAILY observation
JOIN RAW.BERTHS berth ON berth.ID = observation.ENTITY_ID
GROUP BY berth.ID, berth.NAME, berth.REGION, berth.CATEGORY, berth.STATUS;

CREATE DYNAMIC TABLE CURATED.TREND_ANALYSIS
  TARGET_LAG = DOWNSTREAM WAREHOUSE = __DEMO_WH__
  REFRESH_MODE = FULL INITIALIZE = ON_CREATE
AS
SELECT EVENT_DATE AS METRIC_DATE, COUNT(*) AS EVENT_COUNT,
       SUM(ON_TIME_MOVES) AS ON_TIME_MOVES, SUM(BOX_MOVES) AS BOX_MOVES,
       SUM(YARD_MOVES) AS YARD_MOVES, SUM(REHANDLE_MOVES) AS REHANDLE_MOVES,
       SUM(DISRUPTION_COUNT) AS DISRUPTION_COUNT,
       100.0 * SUM(ON_TIME_MOVES) / NULLIF(SUM(BOX_MOVES), 0) AS ON_TIME_PCT
FROM RAW.BERTH_DAILY
GROUP BY EVENT_DATE;

CREATE DYNAMIC TABLE CURATED.DISRUPTION_CAUSES
  TARGET_LAG = DOWNSTREAM WAREHOUSE = __DEMO_WH__
  REFRESH_MODE = FULL INITIALIZE = ON_CREATE
AS
SELECT ROOT_CAUSE, SUM(DISRUPTION_COUNT) AS DISRUPTION_COUNT,
       SUM(DOWNTIME_HOURS) AS DOWNTIME_HOURS,
       SUM(BOX_MOVES) - SUM(ON_TIME_MOVES) AS LATE_MOVES
FROM RAW.BERTH_DAILY
WHERE DISRUPTION_COUNT > 0
GROUP BY ROOT_CAUSE;

CREATE DYNAMIC TABLE CURATED.KPI_SUMMARY
  TARGET_LAG = DOWNSTREAM WAREHOUSE = __DEMO_WH__
  REFRESH_MODE = FULL INITIALIZE = ON_CREATE
AS
WITH observations AS (
  SELECT SUM(ON_TIME_MOVES) AS ON_TIME_MOVES, SUM(BOX_MOVES) AS BOX_MOVES,
         SUM(YARD_MOVES) AS YARD_MOVES, SUM(REHANDLE_MOVES) AS FAILED,
         SUM(DISRUPTION_COUNT) AS DISRUPTIONS,
         SUM(OPERATING_HOURS) AS OPERATING_HOURS, SUM(PLANNED_HOURS) AS PLANNED_HOURS,
         MAX(EVENT_DATE) AS SOURCE_WATERMARK
  FROM RAW.BERTH_DAILY
), network AS (SELECT COUNT(*) AS BERTH_COUNT FROM RAW.BERTHS),
readiness AS (
  SELECT 100.0 * SUM(LEAST(ON_HAND_QTY, REQUIRED_QTY)) / NULLIF(SUM(REQUIRED_QTY), 0) AS COVERAGE_PCT
  FROM RAW.EQUIPMENT_READINESS
), metrics AS (
  SELECT 1 AS SORT_ORDER, 'On-Time Box Moves' AS TITLE,
         100.0 * ON_TIME_MOVES / NULLIF(BOX_MOVES, 0) AS VALUE_NUM, '%' AS UNIT FROM observations
  UNION ALL SELECT 2, 'Berth Disruptions', DISRUPTIONS, '' FROM observations
  UNION ALL SELECT 3, 'Rehandles per 1k Yard Moves', 1000.0 * FAILED / NULLIF(YARD_MOVES, 0), '' FROM observations
  UNION ALL SELECT 4, 'Box Moves Handled', BOX_MOVES, '' FROM observations
  UNION ALL SELECT 5, 'Crane Uptime', 100.0 * OPERATING_HOURS / NULLIF(PLANNED_HOURS, 0), '%' FROM observations
  UNION ALL SELECT 6, 'Berths Monitored', BERTH_COUNT, '' FROM network
  UNION ALL SELECT 7, 'Crane Readiness', COVERAGE_PCT, '%' FROM readiness
)
SELECT metrics.SORT_ORDER, metrics.TITLE, metrics.VALUE_NUM,
       IFF(metrics.VALUE_NUM IS NULL, 'Unavailable',
           CASE WHEN metrics.TITLE = 'Rehandles per 1k Yard Moves' THEN TRIM(TO_VARCHAR(metrics.VALUE_NUM, '990.00'))
                WHEN metrics.UNIT = '' THEN TRIM(TO_VARCHAR(ROUND(metrics.VALUE_NUM), '999,999,999,990'))
                ELSE TRIM(TO_VARCHAR(ROUND(metrics.VALUE_NUM, 1), '990.0')) END || metrics.UNIT) AS DISPLAY,
       'neutral' AS STATUS, observations.SOURCE_WATERMARK
FROM metrics CROSS JOIN observations;

ALTER DYNAMIC TABLE CURATED.PERFORMANCE_SUMMARY SUSPEND;
ALTER DYNAMIC TABLE CURATED.TREND_ANALYSIS SUSPEND;
ALTER DYNAMIC TABLE CURATED.DISRUPTION_CAUSES SUSPEND;
ALTER DYNAMIC TABLE CURATED.KPI_SUMMARY SUSPEND;
